#!/bin/sh
set -eu
mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS auth_db;
CREATE DATABASE IF NOT EXISTS employee_db;
CREATE DATABASE IF NOT EXISTS attendance_db;
CREATE DATABASE IF NOT EXISTS document_db;
CREATE USER IF NOT EXISTS 'auth_app'@'%' IDENTIFIED BY '${MYSQL_AUTH_PASSWORD}';
CREATE USER IF NOT EXISTS 'employee_app'@'%' IDENTIFIED BY '${MYSQL_EMPLOYEE_PASSWORD}';
CREATE USER IF NOT EXISTS 'attendance_app'@'%' IDENTIFIED BY '${MYSQL_ATTENDANCE_PASSWORD}';
CREATE USER IF NOT EXISTS 'document_app'@'%' IDENTIFIED BY '${MYSQL_DOCUMENT_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE ON auth_db.* TO 'auth_app'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE ON employee_db.* TO 'employee_app'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE ON attendance_db.* TO 'attendance_app'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE ON document_db.* TO 'document_app'@'%';
SQL
